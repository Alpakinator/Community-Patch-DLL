"""Proxy / server code generator for the DLL's ICv* interfaces (epic 2100, task 2105: skeleton + proof).

Reads proxy/model/interfaces.json (extract_model.py) and classifies every method with marshal_types.py, then
emits, per interface I:

  ids_I.gen.h          shared by both sides: interface type id, method ids, FNV-1a 64 schema hash
  proxy_I.gen.h/.cpp   x86 proxy side (clang-cl -m32, VC9 headers, C++11): class Proxy_I : public I, one override per
                       virtual, each marshalling with vpipc::Writer -> Channel::begin_call/end_call -> vpipc::Reader
                       (ipc/PROTOCOL.md section 8); plus the model's x86 slot table as a comment and as an array of
                       pointers to members in slot order (for a later runtime check)
  server_I.gen.cpp     x64 server side (clang-cl -m64, MSVC 14 STL, C++14): bool Dispatch_I(method, args, ret, ch),
                       one case per remote method: resolve the handle to the real I* and call it virtually
and once per run:
  ids_schema.gen.h     kAppSchemaHash over all emitted interfaces (EndpointConfig::appSchemaHash)
  server_dispatch.gen.cpp   bool DispatchGenerated(...) routing on the type id in the method id

Wire convention per CALL: handle of `this` (u32 type, i32 id), then the in-parameters in declaration order.
RETURN: the return value, then the out-parameters in declaration order. Scalar references and pointers (out_scalar)
and CvString& (out_str) are in/out (issue 0380): in both, the callee starts from the caller's value; a scalar pointer
crosses as b present [+ value] and comes back only when present. Out arrays (out_array_i32) stay copy-out. Method id = (type id << 16) | method index.
QueryInterface and Destroy are local to the proxy. A method whose codec is not mechanical calls a hand-written hook
(declared here, body NOT generated): ProxyHook_I_M on the proxy side, ServerHook_I_M on the server side.

Usage: python proxy/gen/gen_proxy.py --iface ICvRandom1 [--iface ICvTeam1 ...] --out <dir>
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import marshal_types as mt  # noqa: E402
import toolchain as tc  # noqa: E402

MODEL = os.path.join(tc.PROXY, 'model', 'interfaces.json')
CALLCONV = {'stdcall': 'DLLCALL', 'cdecl': '__cdecl', 'thiscall': ''}
LOCAL = ('QueryInterface', 'Destroy')
HEADER = '// GENERATED by proxy/gen/gen_proxy.py from proxy/model/interfaces.json. Do not edit.\n'

OUT_SCALAR_CODEC = {'int': 'i32', 'bool': 'b', 'float': 'f32', 'size_t': 'u32', 'int32': 'i32'}
# Writer expressions per out_scalar wire codec (%s = the value); the in half of the in/out scalar (issue 0380).
OUT_SCALAR_PUT = {'i32': 'w.i32(static_cast<int32_t>(%s))', 'b': 'w.b(%s)', 'f32': 'w.f32(%s)',
                  'u32': 'w.u32(static_cast<uint32_t>(%s))'}
OUT_SCALAR_GET = {'i32': 'args.i32()', 'b': 'args.b()', 'f32': 'args.f32()', 'u32': 'args.u32()'}


def fnv1a64(data, h=0xcbf29ce484222325):
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def cpp_sig(m, names=True):
    ps = ', '.join(('%s %s' % (p['type'], p['name'])) if names else p['type'] for p in m['params'])
    if m['variadic']:
        ps = ps + ', ...' if ps else '...'
    return ps


def base_type(t):
    """'const CvString &' -> 'CvString'; 'unsigned long' -> 'unsigned long'."""
    t = t.strip()
    if t.endswith('&'):
        t = t[:-1].strip()
    return mt.strip_top_const(t)


def pointee(t):
    m = re.match(r'^(?:const )?(\w+) \*$', t.strip())
    return m.group(1) if m else None


def is_char_ptr(t):
    return t in ('const char *', 'LPCSTR', 'LPCTSTR', 'const TCHAR *', 'const char *const')


class Iface:
    def __init__(self, entry, type_id):
        self.e = entry
        self.name = entry['name']
        self.type_id = type_id
        self.methods = []
        names = [m['name'] for m in entry['methods']]
        for i, m in enumerate(entry['methods']):
            if m['name'].startswith('~'):
                continue
            c = mt.classify_method(m)
            ident = m['name'] if names.count(m['name']) == 1 else '%s_s%d' % (m['name'], m['slot']['x86'])
            local = m['declared_in'] == 'ICvUnknown' and m['name'] in LOCAL
            self.methods.append({'m': m, 'c': c, 'index': i, 'ident': ident, 'local': local,
                                 'id': (type_id << 16) | i,
                                 'const_name': 'kM_%s_%s' % (self.name, ident)})
        self.schema = fnv1a64(self.schema_text().encode('utf-8'))

    def schema_text(self):
        parts = [self.name, str(self.type_id)]
        for x in self.methods:
            m = x['m']
            parts += [m['key'], str(m['slot']['x86']), str(m['slot']['x64']), str(x['id'])]
        return '\0'.join(parts)


# ---------------------------------------------------------------------------------------------------------- ids
def emit_ids(it):
    g = 'VP_IDS_%s_GEN_H' % it.name.upper()
    L = [HEADER, '// Shared by the x86 proxy and the x64 server: ids and schema hash of %s.' % it.name,
         '#pragma once', '#include <stdint.h>', '',
         '#ifndef VP_IFACE_TYPE_DECLARED', '#define VP_IFACE_TYPE_DECLARED',
         '// Interface type id of a handle (u32 type of vpipc::Handle); 0 = null handle.',
         'template <class T> struct VpIfaceType;', '#endif', '',
         'class %s;' % it.name,
         'static const uint32_t kT_%s = %du;' % (it.name, it.type_id),
         'template <> struct VpIfaceType<%s> { enum { value = %d }; };' % (it.name, it.type_id), '',
         '// FNV-1a 64 over: interface name, type id, then per method: key, x86 slot, x64 slot, method id.',
         'static const uint64_t kSchema_%s = 0x%016xULL;' % (it.name, it.schema), '',
         '// Method ids: (type id << 16) | method index. Columns: x86 slot, x64 slot, key, codec verdict.']
    for x in it.methods:
        m = x['m']
        verdict = 'local' if x['local'] else ('mechanical' if x['c']['mechanical'] else 'hook')
        L.append('static const uint32_t %s = 0x%08xu;  // x86 %2d, x64 %2d  %s  [%s]' % (
            x['const_name'], x['id'], m['slot']['x86'], m['slot']['x64'], m['key'], verdict))
    return '\n'.join(L) + '\n'


def emit_schema(ifaces):
    h = 0xcbf29ce484222325
    for it in sorted(ifaces, key=lambda i: i.name):
        h = fnv1a64(it.schema_text().encode('utf-8') + b'\0', h)
    L = [HEADER, '// App schema hash of the generated tables: EndpointConfig::appSchemaHash (PROTOCOL.md 7.2).',
         '#pragma once', '#include <stdint.h>', '']
    L += ['#include "ids_%s.gen.h"' % it.name for it in sorted(ifaces, key=lambda i: i.name)]
    L += ['', '// Interfaces: %s' % ', '.join(sorted(i.name for i in ifaces)),
          'static const uint64_t kAppSchemaHash = 0x%016xULL;' % h]
    return '\n'.join(L) + '\n'


# -------------------------------------------------------------------------------------------------- proxy (x86)
def proxy_hook_decl(it, x):
    m = x['m']
    self_t = ('const ' if m['const'] else '') + 'Proxy_%s& self' % it.name
    ps = cpp_sig(m)
    return '%s ProxyHook_%s_%s(%s%s)' % (m['ret'], it.name, x['ident'], self_t, (', ' + ps) if ps else '')


def emit_proxy_h(it):
    L = [HEADER, '// x86 proxy side (clang-cl -m32, VC9 headers, C++11) of %s.' % it.name, '#pragma once',
         '#include "proxy_runtime.h"', '#include "ids_%s.gen.h"' % it.name, '',
         '// Presents %s to the EXE and forwards each call to the server. Deriving from the real interface makes the' %
         it.name,
         '// compiler check every override (signature, const, calling convention): a mismatch does not compile.',
         'class Proxy_%s : public %s' % (it.name, it.name), '{', 'public:',
         '    explicit Proxy_%s(vpipc::Handle h) : m_h(h) {}' % it.name,
         '    vpipc::Handle ProxyHandle() const { return m_h; }', '']
    for x in it.methods:
        m = x['m']
        L.append('    virtual %s %s %s(%s)%s override;' % (m['ret'], CALLCONV[m['callconv']], m['name'], cpp_sig(m),
                                                         ' const' if m['const'] else ''))
    L += ['', 'private:', '    Proxy_%s(const Proxy_%s&);' % (it.name, it.name),
          '    Proxy_%s& operator=(const Proxy_%s&);' % (it.name, it.name), '    vpipc::Handle m_h;', '};', '']
    hooks = [x for x in it.methods if not x['local'] and not x['c']['mechanical']]
    if hooks:
        L.append('// Hand-written hooks (body NOT generated) for the methods whose codec is not mechanical.')
        for x in hooks:
            L.append('// %s: %s' % (x['m']['key'], '; '.join(x['c']['reasons'])))
            L.append('%s;' % proxy_hook_decl(it, x))
        L.append('')
    L += ['// The model\'s x86 vftable slots, as pointers to members in slot order (for a later runtime check).',
          'typedef void (%s::*ProxyAnyPmf_%s)();' % (it.name, it.name),
          'struct ProxySlot_%s { uint32_t slotX86; uint32_t method; const char* key; ProxyAnyPmf_%s pmf; };' % (
              it.name, it.name),
          'const ProxySlot_%s* ProxySlots_%s(uint32_t* count);' % (it.name, it.name)]
    return '\n'.join(L) + '\n'


def enc_in(p, var):
    """Proxy-side encoding of one in-parameter; None when it sends nothing."""
    c, t = p['codec'], p['type']
    if c == 'i32':
        return 'w.i32(static_cast<int32_t>(%s));' % var
    if c == 'bool':
        return 'w.b(%s);' % var
    if c in ('f32', 'f64', 'u64'):
        return 'w.%s(%s);' % (c, var)
    if c == 'str':
        return ('w.str(%s);' % var) if is_char_ptr(t) else \
            'w.str(%s.c_str(), static_cast<uint32_t>(%s.size()));' % (var, var)
    if c == 'wstr':
        return 'w.wstr(%s);' % var
    if c == 'guid':
        return 'w.bytes(&%s, 16u);' % var
    if c == 'handle':
        return 'w.handle(ProxyRuntime::HandleOf(%s));' % var
    if c == 'out_scalar':
        # In/out (issue 0380): the callee starts from the caller's value, as it would in-process; a DLL method that
        # returns without writing it leaves the caller's value (ICvPreGame1::GetMapOption's unset option).
        b = base_type(t.rstrip('*').strip())
        put = OUT_SCALAR_PUT[OUT_SCALAR_CODEC[b]]
        if t.endswith('*'):
            return 'w.b(%s != NULL); if (%s) %s;' % (var, var, put % ('*' + var))
        return put % var + ';'
    if c == 'out_str':
        return 'w.str(%s.c_str(), static_cast<uint32_t>(%s.size()));' % (var, var)
    if c == 'out_array_i32':
        return None
    raise ValueError('no proxy encoder for codec %s (%s)' % (c, t))


def dec_ret_proxy(codec, ret):
    if codec == 'i32':
        return 'static_cast<R>(r.i32())'
    if codec == 'bool':
        return 'r.b()'
    if codec in ('f32', 'f64', 'u64'):
        return 'static_cast<R>(r.%s())' % codec
    if codec == 'str_ret_interned':
        return 'ProxyRuntime::InternString(r.cstr())'
    if codec == 'wstr_ret_interned':
        return 'ProxyRuntime::InternWString(r.wcstr())'
    if codec == 'handle':
        return 'static_cast<R>(ProxyRuntime::Wrap(r.handle()))'
    raise ValueError('no proxy decoder for return codec %s (%s)' % (codec, ret))


def dec_out_proxy(p):
    c, t, n = p['codec'], p['type'], p['name']
    if c == 'out_str':
        return ['{ const char* s_ = r.cstr(); %s = s_ ? s_ : ""; }' % n]
    if c == 'out_scalar':
        b = base_type(t.rstrip('*').strip())
        rd = {'i32': 'r.i32()', 'b': 'r.b()', 'f32': 'r.f32()', 'u32': 'r.u32()'}[OUT_SCALAR_CODEC[b]]
        if t.endswith('*'):
            return ['if (%s) *%s = static_cast<%s>(%s);  // sent back only when present' % (n, n, b, rd)]
        return ['%s = static_cast<%s>(%s);' % (n, b, rd)]
    if c == 'out_array_i32':
        cnt = p['count_param']
        return ['{',
                '    uint32_t len_ = 0;',
                '    const uint8_t* src_ = r.bytes(&len_);',
                '    const uint32_t cap_ = static_cast<uint32_t>(%s) * 4u;' % cnt,
                '    if (src_ && %s) memcpy(%s, src_, len_ < cap_ ? len_ : cap_);' % (n, n),
                '}']
    return []


def emit_proxy_cpp(it):
    L = [HEADER, '// x86 proxy side of %s. Built with clang-cl -m32 in the VS 2008 environment (VC9, _MSC_VER 1500).' %
         it.name,
         '#include "CvGameCoreDLLPCH.h"', '#include <string.h>', '#include "proxy_%s.gen.h"' % it.name, '',
         '#if !defined(_MSC_VER) || _MSC_VER != 1500 || !defined(_M_IX86)',
         '#error "proxy side must be built for x86 against the VC9 headers (_MSC_VER 1500)"', '#endif', '']
    chain = it.e['chain']
    for x in it.methods:
        m = x['m']
        cc = CALLCONV[m['callconv']]
        head = '%s %s Proxy_%s::%s(%s)%s' % (m['ret'], cc, it.name, m['name'], cpp_sig(m), ' const' if m['const'] else '')
        L.append('// %s  x86 slot %d, x64 slot %d' % (m['key'], m['slot']['x86'], m['slot']['x64']))
        L.append(head)
        L.append('{')
        if x['local'] and m['name'] == 'QueryInterface':
            L.append('    // Local: this wrapper answers for its own interface chain (%s).' % ', '.join(chain))
            for base in chain:
                L.append('    if (memcmp(&guidInterface, &guid%s, sizeof(GUID)) == 0) return static_cast<%s*>(this);' % (
                    base, base))
            L.append('    return NULL;')
        elif x['local'] and m['name'] == 'Destroy':
            L.append('    // Local: the EXE releases the wrapper; the runtime tells the server the handle is gone.')
            L.append('    ProxyRuntime::Release(m_h);')
            L.append('    delete this;')
        elif not x['c']['mechanical']:
            args = ', '.join(['*this'] + [p['name'] for p in m['params']])
            L.append('    // Not mechanical: %s' % '; '.join(x['c']['reasons']))
            L.append('    %sProxyHook_%s_%s(%s);' % ('' if m['ret'] == 'void' else 'return ', it.name, x['ident'], args))
        else:
            c = x['c']
            if m['ret'] != 'void':
                L.append('    typedef %s R;' % m['ret'])
            L.append('    vpipc::Channel& ch = ProxyRuntime::CurrentChannel();')
            L.append('    vpipc::Writer& w = ch.begin_call(%s);' % x['const_name'])
            L.append('    w.handle(m_h);')
            for p in c['params']:
                s = enc_in(p, p['name'])
                if s:
                    L.append('    ' + s)
            L.append('    vpipc::Reader r;')
            L.append('    const vpipc::Status st = ch.end_call(r);')
            L.append('    if (st != vpipc::Status::Ok)')
            L.append('    {')
            L.append('        ProxyRuntime::CallFailed(%s, st);' % x['const_name'])
            L.append('        return%s;' % ('' if m['ret'] == 'void' else ' R()'))
            L.append('    }')
            if c['ret_codec'] != 'void':
                L.append('    const R ret = %s;' % dec_ret_proxy(c['ret_codec'], m['ret']))
            for p in c['params']:
                for s in dec_out_proxy(p):
                    L.append('    ' + s)
            L.append('    if (!r.ok()) ProxyRuntime::DecodeFailed(%s);' % x['const_name'])
            if c['ret_codec'] != 'void':
                L.append('    return ret;')
        L.append('}')
        L.append('')
    # slot table
    L.append('// x86 vftable slots from the model (clang dump, confirmed by MSVC vcall thunks: slot-proof.json):')
    L.append('//  slot  method id   key')
    for x in sorted(it.methods, key=lambda x: x['m']['slot']['x86']):
        L.append('//  %4d  0x%08x  %s' % (x['m']['slot']['x86'], x['id'], x['m']['key']))
    L.append('namespace {')
    for k, x in enumerate(sorted(it.methods, key=lambda x: x['m']['slot']['x86'])):
        m = x['m']
        L.append('typedef %s (%s %s::*Pmf%d)(%s)%s;' % (m['ret'], CALLCONV[m['callconv']], it.name, k,
                                                        cpp_sig(m, names=False), ' const' if m['const'] else ''))
    L.append('const ProxySlot_%s kSlots[] = {' % it.name)
    for k, x in enumerate(sorted(it.methods, key=lambda x: x['m']['slot']['x86'])):
        m = x['m']
        L.append('    {%du, %s, "%s", reinterpret_cast<ProxyAnyPmf_%s>(static_cast<Pmf%d>(&%s::%s))},' % (
            m['slot']['x86'], x['const_name'], m['key'], it.name, k, it.name, m['name']))
    L.append('};')
    L.append('}  // namespace')
    L.append('const ProxySlot_%s* ProxySlots_%s(uint32_t* count)' % (it.name, it.name))
    L.append('{')
    L.append('    *count = static_cast<uint32_t>(sizeof(kSlots) / sizeof(kSlots[0]));')
    L.append('    return kSlots;')
    L.append('}')
    return '\n'.join(L) + '\n'


# ------------------------------------------------------------------------------------------------- server (x64)
def server_hook_decl(it, x):
    return 'bool ServerHook_%s_%s(%s%s* self, vpipc::Reader& args, vpipc::Writer& ret, vpipc::Channel& ch)' % (
        it.name, x['ident'], 'const ' if x['m']['const'] else '', it.name)


def dec_in_server(p):
    """Server-side declaration + decoding of one parameter (before the call). Returns (lines, call_arg, check)."""
    c, t, n = p['codec'], p['type'], p['name']
    if c == 'i32':
        b = base_type(t)
        return ['%s %s = static_cast<%s>(args.i32());' % (b, n, b)], n, None
    if c == 'bool':
        return ['bool %s = args.b();' % n], n, None
    if c in ('f32', 'f64', 'u64'):
        b = base_type(t)
        return ['%s %s = static_cast<%s>(args.%s());' % (b, n, b, c)], n, None
    if c == 'str':
        if is_char_ptr(t):
            return ['const char* %s = args.cstr();' % n], n, None
        b = base_type(t)
        return ['const char* %s_c = args.cstr();' % n, '%s %s(%s_c ? %s_c : "");' % (b, n, n, n)], n, None
    if c == 'wstr':
        return ['const wchar_t* %s = args.wcstr();' % n], n, None
    if c == 'guid':
        return ['GUID %s; memset(&%s, 0, sizeof(%s));' % (n, n, n),
                '{ uint32_t len_ = 0; const uint8_t* g_ = args.bytes(&len_); if (g_ && len_ == 16u) memcpy(&%s, g_, 16u); }'
                % n], n, None
    if c == 'handle':
        it = pointee(t)
        return ['const vpipc::Handle %s_h = args.handle();' % n,
                '%s* %s = ServerHandles::Resolve<%s>(%s_h.type, %s_h.id);' % (it, n, it, n, n)], n, \
            '(%s_h.type != 0u && !%s)' % (n, n)
    if c == 'out_scalar':
        # In/out (issue 0380): starts from the caller's value; a pointer keeps its presence (NULL stays NULL).
        b = base_type(t.rstrip('*').strip())
        get = OUT_SCALAR_GET[OUT_SCALAR_CODEC[b]]
        if t.endswith('*'):
            return ['%s %s_v = %s();' % (b, n, b), '%s* %s = NULL;' % (b, n),
                    'if (args.b()) { %s_v = static_cast<%s>(%s); %s = &%s_v; }' % (n, b, get, n, n)], n, None
        return ['%s %s = static_cast<%s>(%s);' % (b, n, b, get)], n, None
    if c == 'out_str':
        return ['const char* %s_c = args.cstr();' % n, 'CvString %s(%s_c ? %s_c : "");' % (n, n, n)], n, None
    if c == 'out_array_i32':
        el = pointee(t)
        return ['std::vector<%s> %s;  // sized after the count is decoded' % (el, n)], \
            '(%s.empty() ? nullptr : &%s[0])' % (n, n), None
    raise ValueError('no server decoder for codec %s (%s)' % (c, t))


def enc_ret_server(codec, ret):
    if codec == 'i32':
        return 'ret.i32(static_cast<int32_t>(r_));'
    if codec == 'bool':
        return 'ret.b(r_);'
    if codec in ('f32', 'f64', 'u64'):
        return 'ret.%s(r_);' % codec
    if codec in ('str_ret_interned',):
        return 'ret.str(r_);'
    if codec in ('wstr_ret_interned',):
        return 'ret.wstr(r_);'
    if codec == 'handle':
        return 'ret.handle(ServerHandles::Register(r_));'
    raise ValueError('no server encoder for return codec %s (%s)' % (codec, ret))


def enc_out_server(p):
    c, t, n = p['codec'], p['type'], p['name']
    if c == 'out_scalar':
        b = base_type(t.rstrip('*').strip())
        v = ('*%s' % n) if t.endswith('*') else n
        s = 'ret.%s(%s);' % (OUT_SCALAR_CODEC[b], v if OUT_SCALAR_CODEC[b] in ('b', 'f32') else
                             'static_cast<%s>(%s)' % ('uint32_t' if OUT_SCALAR_CODEC[b] == 'u32' else 'int32_t', v))
        return [('if (%s) ' % n + s) if t.endswith('*') else s]
    if c == 'out_str':
        return ['ret.str(%s.c_str(), static_cast<uint32_t>(%s.size()));' % (n, n)]
    if c == 'out_array_i32':
        el = pointee(t)
        return ['static_assert(sizeof(%s) == 4, "out_array_i32 element must be 4 bytes");' % el,
                'ret.bytes(%s.empty() ? nullptr : &%s[0], static_cast<uint32_t>(%s.size() * 4u));' % (n, n, n)]
    return []


def emit_server_cpp(it):
    L = [HEADER, '// x64 server side of %s. Built with clang-cl -m64, MSVC 14.4x STL, /std:c++14.' % it.name,
         '#include "CvGameCoreDLLPCH.h"', '#include <string.h>', '#include <vector>', '#include "server_runtime.h"',
         '#include "ids_%s.gen.h"' % it.name, '',
         '#if !defined(_MSC_VER) || _MSC_VER < 1900 || !defined(_M_X64)',
         '#error "server side must be built for x64 against the MSVC 14 STL"', '#endif', '']
    hooks = [x for x in it.methods if not x['local'] and not x['c']['mechanical']]
    if hooks:
        L.append('// Hand-written hooks (body NOT generated). `self` is resolved; they decode the rest of `args`.')
        for x in hooks:
            L.append('%s;' % server_hook_decl(it, x))
        L.append('')
    L += ['// Returns false for a method id this interface does not serve (the caller answers "unknown method").',
          'bool Dispatch_%s(uint32_t method, vpipc::Reader& args, vpipc::Writer& ret, vpipc::Channel& ch)' % it.name,
          '{', '    switch (method)', '    {']
    for x in it.methods:
        m = x['m']
        if x['local']:
            L.append('    // %s: local to the proxy, never sent.' % x['const_name'])
            continue
        L.append('    case %s:  // %s, x64 slot %d' % (x['const_name'], m['key'], m['slot']['x64']))
        L.append('    {')
        L.append('        const vpipc::Handle self_h = args.handle();')
        L.append('        %s* self = ServerHandles::Resolve<%s>(self_h.type, self_h.id);' % (it.name, it.name))
        if not x['c']['mechanical']:
            L.append('        if (!self) return ServerDispatchFail(ch, ret, "%s: bad handle");' % x['const_name'])
            L.append('        return ServerHook_%s_%s(self, args, ret, ch);' % (it.name, x['ident']))
            L.append('    }')
            continue
        c = x['c']
        call_args, checks, post = [], [], []
        for p in c['params']:
            lines, arg, chk = dec_in_server(p)
            L += ['        ' + s for s in lines]
            call_args.append(arg)
            if chk:
                checks.append(chk)
        for p in c['params']:
            if p['codec'] == 'out_array_i32':
                cnt = p['count_param']
                L.append('        if (static_cast<uint32_t>(%s) > (1u << 20)) return ServerDispatchFail(ch, ret, "%s: count");'
                         % (cnt, x['const_name']))
                L.append('        %s.resize(static_cast<size_t>(%s));' % (p['name'], cnt))
        cond = ' || '.join(['!args.ok()', '!self'] + checks)
        L.append('        if (%s) return ServerDispatchFail(ch, ret, "%s: bad arguments or handle");' % (cond, x['const_name']))
        call = 'self->%s(%s)' % (m['name'], ', '.join(call_args))
        if c['ret_codec'] == 'void':
            L.append('        %s;' % call)
        else:
            L.append('        typedef %s R_;' % m['ret'])
            L.append('        const R_ r_ = %s;' % call)
            L.append('        ' + enc_ret_server(c['ret_codec'], m['ret']))
        for p in c['params']:
            post += enc_out_server(p)
        L += ['        ' + s for s in post]
        L.append('        return true;')
        L.append('    }')
    L += ['    default:', '        return false;', '    }', '}']
    return '\n'.join(L) + '\n'


def emit_server_dispatch(ifaces):
    L = [HEADER, '// x64 server: routes a CALL to the generated dispatcher of its interface (method id >> 16).',
         '#include "server_runtime.h"', '']
    for it in ifaces:
        L.append('bool Dispatch_%s(uint32_t method, vpipc::Reader& args, vpipc::Writer& ret, vpipc::Channel& ch);' %
                 it.name)
    L += ['', 'bool DispatchGenerated(uint32_t method, vpipc::Reader& args, vpipc::Writer& ret, vpipc::Channel& ch)', '{',
          '    switch (method >> 16)', '    {']
    for it in ifaces:
        L.append('    case %du: return Dispatch_%s(method, args, ret, ch);' % (it.type_id, it.name))
    L += ['    default: return false;', '    }', '}']
    return '\n'.join(L) + '\n'


