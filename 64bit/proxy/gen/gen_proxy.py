def write(path, text):
    bad = [c for c in text if ord(c) < 32 and c not in '\n']
    if bad:
        raise RuntimeError('control characters in generated %s: %r' % (path, sorted(set(bad))))
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    return text.count('\n')


def generate(names, out):
    with open(MODEL, encoding='utf-8') as f:
        model = json.load(f)
    order = [e['name'] for e in model['interfaces']]
    by = {e['name']: e for e in model['interfaces']}
    ifaces = []
    for n in names:
        if n not in by:
            raise SystemExit('interface %s not in the model' % n)
        ifaces.append(Iface(by[n], order.index(n) + 1))  # type id = 1-based position in the model
    os.makedirs(out, exist_ok=True)
    written = {}
    for it in ifaces:
        written['ids_%s.gen.h' % it.name] = emit_ids(it)
        written['proxy_%s.gen.h' % it.name] = emit_proxy_h(it)
        written['proxy_%s.gen.cpp' % it.name] = emit_proxy_cpp(it)
        written['server_%s.gen.cpp' % it.name] = emit_server_cpp(it)
    written['ids_schema.gen.h'] = emit_schema(ifaces)
    written['server_dispatch.gen.cpp'] = emit_server_dispatch(ifaces)
    counts = {}
    for fn, text in written.items():
        counts[fn] = write(os.path.join(out, fn), text)
    return ifaces, counts


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--iface', action='append', required=True, help='interface name (repeatable)')
    ap.add_argument('--out', required=True, help='output directory')
    a = ap.parse_args()
    ifaces, counts = generate(a.iface, a.out)
    for it in ifaces:
        hooks = [x['ident'] for x in it.methods if not x['local'] and not x['c']['mechanical']]
        print('%s: type %d, %d methods, schema 0x%016x, hooks: %s' % (it.name, it.type_id, len(it.methods), it.schema,
                                                                       ', '.join(hooks) or '-'))
    for fn in sorted(counts):
        print('  %-32s %5d lines' % (fn, counts[fn]))


if __name__ == '__main__':
    main()
