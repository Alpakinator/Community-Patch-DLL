"""The build-id header both builds generate (issue 2704): <dir>/vp_build_info.h, read by proxy/include/vp_buildid.h.

    from build_info import write_header
    write_header(<dir>, srcinfo, config)    # srcinfo: tools/x64-dll/build.py resolve_src's dict

Fields: this repository's commit (git rev-parse --short=9 HEAD), whether it has tracked changes (dirty=1; untracked files
are not counted), the DLL pin (deps/dll.lock `commit`, 9 digits), the --src mode (git, git-unlocked with its HEAD, copy),
the build config and a build time that repeats (issue 0115: SOURCE_DATE_EPOCH, else the commit time). The SHA-256 of the binary itself is computed at run time (vp_buildid.h): a hash
cannot be embedded in the file it hashes. Python standard library only.

    python proxy/gen/build_info.py <dir>      # writes the header with src "unknown" (for a look at the values)
"""
import os
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]


def _git(*args):
    try:
        cp = subprocess.run(['git', '-C', str(REPO)] + list(args), capture_output=True, text=True, errors='replace')
        return cp.stdout.strip() if cp.returncode == 0 else None
    except OSError:
        return None


def _lock_commit():
    for line in (REPO / 'deps' / 'dll.lock').read_text(encoding='utf-8').splitlines():
        k, _, v = line.partition('=')
        if k.strip() == 'commit':
            return v.strip()
    return ''


def build_time():
    """VP_BUILD_TIME (issue 0115, 2026-11-13): not the wall clock any more, so that two builds of one commit give the
    same bytes. SOURCE_DATE_EPOCH (seconds, the reproducible-builds convention) when set, else the commit time of HEAD
    (`git log -1 --format=%cI`), else "unknown" (a copy without .git). Was: time.strftime at build time."""
    sde = os.environ.get('SOURCE_DATE_EPOCH', '').strip()
    if sde.isdigit():
        return time.strftime('%Y-%m-%dT%H:%M:%S+0000', time.gmtime(int(sde)))
    return _git('log', '-1', '--format=%cI', 'HEAD') or 'unknown'


def values(srcinfo=None, config='unknown'):
    head = _git('rev-parse', '--short=9', 'HEAD') or 'unknown'
    status = _git('status', '--porcelain', '--untracked-files=no')
    dirty = 'unknown' if status is None else ('1' if status else '0')
    pin = (srcinfo or {}).get('lock_commit') or _lock_commit()
    src = 'unknown'
    if srcinfo:
        src = srcinfo.get('mode', 'unknown')
        if src == 'git-unlocked':
            src += ' %s%s' % ((srcinfo.get('head') or '?')[:9], '+changes' if srcinfo.get('dirty') else '')
    return {'VP_BUILD_REPO_COMMIT': head, 'VP_BUILD_REPO_DIRTY': dirty, 'VP_BUILD_DLL_PIN': pin[:9] or 'unknown',
            'VP_BUILD_SRC': src, 'VP_BUILD_CONFIG': config, 'VP_BUILD_TIME': build_time()}


def write_header(out_dir, srcinfo=None, config='unknown'):
    """Writes <out_dir>/vp_build_info.h; returns (path, values)."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    v = values(srcinfo, config)
    lines = ['// GENERATED by proxy/gen/build_info.py (issue 2704). Do not edit.', '#pragma once']
    lines += ['#define %s "%s"' % (k, str(x).replace('\\', '/').replace('"', "'")) for k, x in v.items()]
    p = out_dir / 'vp_build_info.h'
    p.write_text('\n'.join(lines) + '\n', encoding='ascii', errors='replace')
    return p, v


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    path, vals = write_header(sys.argv[1])
    print(path)
    for k, x in vals.items():
        print('%s = %s' % (k, x))
