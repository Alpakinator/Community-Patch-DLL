def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def short_path(p):
    import ctypes
    b = ctypes.create_unicode_buffer(1024)
    n = ctypes.windll.kernel32.GetShortPathNameW(str(p), b, 1024)
    return b.value if n else ''


def write_cfg(run_dir_text, run, binp, save_text, defaults, turns):
    """server.cfg in hostruns.py's keys; run_dir_text is written as given (the form under test)."""
    (run / 'db').mkdir(parents=True, exist_ok=True)
    shutil.copyfile(defaults['db'], run / 'db' / 'Civ5DebugDatabase.db')
    shutil.copyfile(defaults['loc_db'], run / 'db' / 'Localization-Merged.db')
    cfg = {'load_save': save_text, 'load_file_name': save_text, 'save_dlc_exclude': 'DLC_SP_Maps',
           'run_dir': run_dir_text, 'game_dir': defaults['game_dir'],
           'dll': str(binp / 'CvGameCore_Expansion2.dll'), 'lua_dll': str(binp / 'lua51_x64.dll'),
           'db_dll': str(binp / 'CvGameDatabase_x64.dll'), 'db': run_dir_text + '\\db\\Civ5DebugDatabase.db',
           'loc_dll': str(binp / 'CvLocalization_x64.dll'), 'loc_db': run_dir_text + '\\db\\Localization-Merged.db',
           'turns': turns, 'idle_updates': 10, 'dll_logs': 0, 'dll_log_flags': 0}
    (run / 'server.cfg').write_text('# written by server/tests/runfolder/run_runfolder_test.py (ticket 0488)\n' +
                                    ''.join('%s=%s\n' % kv for kv in cfg.items()), encoding='utf-8')


def start_server(tag, binp, run, cap, gate, timeout=600):
    gate.require('0488 run-folder live test %s (server.exe)' % tag, None, memory=False)
    gate.require_memory('0488 run-folder live test %s (server.exe)' % tag, floor_gb=2.0)
    logs = []
    t0 = time.time()
    with open(run / 'console.txt', 'w', encoding='utf-8', errors='replace') as con:
        p = jobcap.popen([str(binp / 'server.exe'), '--config', str(run / 'server.cfg')], cap, grace_s=10.0,
                         log=logs.append, cwd=str(run), stdout=con, stderr=subprocess.STDOUT, creationflags=NOWIN)
        try:
            rc = p.wait(timeout)
        except subprocess.TimeoutExpired:
            p.kill()  # a headless server.exe of this test, never a game EXE
            rc = p.wait()
        time.sleep(0.3)
        peak = p.jobcap.peak_process_bytes()
        events = list(p.jobcap.events)
        p.jobcap.close()
    wall = time.time() - t0
    rep = run / 'server-report.txt'
    log = run / 'server.log'
    info = {'rc': rc, 'wall': wall, 'peak': peak, 'events': events, 'logs': logs,
            'report': rep.read_text(encoding='utf-8', errors='replace') if rep.exists() else '',
            'log': log.read_text(encoding='utf-8', errors='replace') if log.exists() else ''}
    m = re.search(r'peak working set (\d+) MB', info['report'] + info['log'])
    info['peak_ws_mb'] = int(m.group(1)) if m else -1
    (run.parent / ('%s-summary.txt' % tag)).write_text(
        'exit %s (0x%08X), wall %.1f s, job peak process commit %.0f MB, peak working set %s MB, cap events %s\n%s\n'
        % (rc, rc & 0xFFFFFFFF, wall, peak / 1048576.0, info['peak_ws_mb'], events, '\n'.join(logs)),
        encoding='utf-8')
    return info


def symbolize(run, binp):
    if not SYMBOLIZER.exists():
        return ''
    out = []
    for line in (run / 'server.log').read_text(encoding='utf-8', errors='replace').splitlines():
        m = re.search(r'(\S+\.(?:dll|exe))\+0x([0-9a-f]+)', line)
        if ('frame' in line or 'EXCEPTION' in line) and m and (binp / m.group(1)).exists():
            r = subprocess.run([str(SYMBOLIZER), '--obj=%s' % (binp / m.group(1)), '--relative-address',
                                '0x' + m.group(2)], capture_output=True, text=True, creationflags=NOWIN)
            line += '   ' + ' '.join(r.stdout.split())
        out.append(line)
    text = '\n'.join(out) + '\n'
    (run / 'server-symbolized.log').write_text(text, encoding='utf-8')
    return text


def live(out, fixed, pin, saves):
    sys.path.insert(0, str(REPO / 'perf' / 'quietlock'))
    import gate  # noqa: E402
    rs = _load('run_server', REPO / 'server' / 'run_server.py')
    defaults = {'db': rs.DEFAULT_DB, 'loc_db': rs.DEFAULT_LOC_DB, 'game_dir': rs.GAME_DIR}
    save = (saves / 'TS0438-M-T150.Civ5Save').resolve()
    if not check('live: the M save is there (%s)' % save, save.is_file()):
        return
    copy = out / 'save'
    copy.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(save, copy / save.name)
    save_slash = str(copy / save.name).replace('\\', '/')
    gb = 1 << 30

    def fresh(tag):
        run = out / tag / 'run'
        if run.parent.exists():
            shutil.rmtree(run.parent)
        run.mkdir(parents=True)
        return run

    # L1: the incident's form with the fixed server
    run = fresh('L1')
    write_cfg(str(run).replace('\\', '/'), run, fixed, save_slash, defaults, 151)
    i = start_server('L1', fixed, run, 8 * gb, gate)
    check('L1 fixed server, run_dir with "/": exit 0, "result: passed" (exit %s, %.1f s)' % (i['rc'], i['wall']),
          i['rc'] == 0 and 'result: passed' in i['report'], i['report'][-1500:])
    check('L1: no refused or failed create in server.log', 'Create(' not in i['log'],
          [x for x in i['log'].splitlines() if 'Create(' in x])
    check('L1: cache\\Civ5SavedGameDatabase.db written', (run / 'cache' / 'Civ5SavedGameDatabase.db').is_file())
    check('L1: no cap event', not i['events'], i['events'])

    # L1s: 8.3 short form, lower case
    run = fresh('L1s')
    sp = short_path(run)
    if check('L1s: the run folder has an 8.3 form (%s)' % sp, bool(sp) and sp.upper() != str(run).upper()):
        write_cfg(sp.lower(), run, fixed, save_slash, defaults, 151)
        i = start_server('L1s', fixed, run, 8 * gb, gate)
        check('L1s fixed server, run_dir short and lower case: exit 0, "result: passed" (exit %s)' % i['rc'],
              i['rc'] == 0 and 'result: passed' in i['report'], i['report'][-1500:])
        check('L1s: no refused create', 'Create(' not in i['log'],
              [x for x in i['log'].splitlines() if 'Create(' in x])

    # L2: the create fails: a folder where the database file goes
    run = fresh('L2')
    (run / 'cache' / 'Civ5SavedGameDatabase.db').mkdir(parents=True)
    write_cfg(str(run), run, fixed, str(copy / save.name), defaults, 151)
    i = start_server('L2', fixed, run, 8 * gb, gate)
    check('L2 fixed server, the create fails: exit 2 (exit %s, %.1f s)' % (i['rc'], i['wall']), i['rc'] == 2,
          i['report'][-1500:])
    check('L2: the report names the failed create and stops the load',
          re.search(r'load: FIFileSystem::Create\(".*Civ5SavedGameDatabase\.db"\) failed: CreateFileW error \d+; .*'
                    r'the load stops here \(ticket 0488\)', i['report']) is not None and
          'FAILED: the save could not be read' in i['report'] and 'result: FAILED' in i['report'],
          i['report'][-2000:])
    check('L2: no exception, no map read (no InitPlots allocation)', 'EXCEPTION' not in i['log'], i['log'][-1500:])
    check('L2: bounded memory: peak working set %s MB < 2048, job peak commit %.0f MB < 2048, no cap event'
          % (i['peak_ws_mb'], i['peak'] / 1048576.0),
          0 < i['peak_ws_mb'] < 2048 and 0 < i['peak'] < 2 * gb and not i['events'], i['events'])
    check('L2: ends within 120 s (%.1f s)' % i['wall'], i['wall'] < 120)

    if pin:
        # L3: the server before the fix, the incident's form, held at a 4 GB cap
        run = fresh('L3')
        write_cfg(str(run).replace('\\', '/'), run, pin, save_slash, defaults, 151)
        i = start_server('L3', pin, run, 4 * gb, gate)
        sym = symbolize(run, pin) if 'EXCEPTION' in i['log'] else ''
        check('L3 pin server, run_dir with "/": the create is refused ("only files inside the run folder")',
              re.search(r'FIFileSystem::Create\(L".*Civ5SavedGameDatabase\.db"\) refused or failed', i['log'])
              is not None, i['log'][-1500:])
        check('L3: the load does not pass (exit %s, 0x%08X, %.1f s)' % (i['rc'], i['rc'] & 0xFFFFFFFF, i['wall']),
              i['rc'] != 0 and 'result: passed' not in i['report'], i['report'][-1500:])
        asserts = run / 'CvAssert.log'
        check("L3: the DLL asserts 'Cannot open Civ5SavedGameDatabase.db for write'",
              asserts.exists() and 'Cannot open Civ5SavedGameDatabase.db for write' in
              asserts.read_text(encoding='utf-8', errors='replace'))
        check('L3: held at the cap: job peak process commit %.0f MB <= 4096' % (i['peak'] / 1048576.0),
              0 < i['peak'] <= 4 * gb)
        check('L3: the cap was reached (a jobcap event for server.exe)',
              any(e['image'].lower() == 'server.exe' for e in i['events']), i['events'])
        check('L3: the failing allocation is in CvMap::InitPlots (symbolized frames)',
              'CvMap::InitPlots' in sym or any('ended by jobcap' in e['action'] for e in i['events']),
              sym[-2500:] or i['events'])


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--asan', action='store_true')
    ap.add_argument('--live', action='store_true')
    ap.add_argument('--bin', type=Path, help='--live: the fixed server layout (server.exe and the pin DLLs)')
    ap.add_argument('--pin-bin', type=Path, help='--live: a server layout before the fix (L3)')
    ap.add_argument('--saves', type=Path, help='--live: folder with TS0438-M-T150.Civ5Save')
    ap.add_argument('-v', action='store_true')
    a = ap.parse_args()
    rt.VERBOSE = a.v
    out = a.out.resolve()
    if REPO in out.parents or out == REPO:
        print('run_runfolder_test: --out must be outside the repository')
        return 2
    out.mkdir(parents=True, exist_ok=True)
    if a.live:
        if not (a.bin and a.saves):
            print('run_runfolder_test: --live needs --bin and --saves')
            return 2
        live(out, a.bin.resolve(), a.pin_bin.resolve() if a.pin_bin else None, a.saves)
    else:
        unit(out)
        if a.asan:
            unit_asan(out)
    bad = [nm for nm, ok in rt.RESULTS if not ok]
    print('run_runfolder_test: %d/%d checks passed' % (len(rt.RESULTS) - len(bad), len(rt.RESULTS)))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
