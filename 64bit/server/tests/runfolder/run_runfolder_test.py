HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
SRC = REPO / 'server' / 'src' / 'srv_ifaces.cpp'
BLOCK = re.compile(r'^// BEGIN 0488 RUN FOLDER.*?^// END 0488 RUN FOLDER$', re.S | re.M)
sys.path.insert(0, str(REPO / 'proxy' / 'tools'))
sys.path.insert(0, str(REPO / 'tools' / 'harness'))
import test_proxy_rt as rt  # noqa: E402  (toolchain, vcvarsall, check())
