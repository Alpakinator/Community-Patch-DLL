"""Ticket 0488: the server's run-folder check and what a refused create does to a load.

    python -I server/tests/runfolder/run_runfolder_test.py --out DIR [--asan]
    python -I server/tests/runfolder/run_runfolder_test.py --out DIR --live --bin FIXED_BIN [--pin-bin PIN_BIN] --saves DIR

1. Unit (always). Extracts the block "0488 RUN FOLDER" of server/src/srv_ifaces.cpp into DIR/runfolder.gen.h (the
   server's own text), builds server/tests/runfolder/test_runfolder.cpp with it (clang-cl x64, /W3 /WX as the server's
   own code) and runs it on DIR/work: mixed separators in either direction and the incident's exact form accepted,
   trailing and repeated separators, case, dots, a file not yet created, 8.3 short names both ways; a sibling with the
   root's name as prefix, '..' out of the root, the root itself, another folder, an empty or NULL root refused.
   --asan: the same program under MSVC /fsanitize=address (x64) after a canary is caught; every case again, no report.
2. Live (--live; gated by perf/quietlock/gate.py, each server.exe under tools/harness/jobcap.py). A headless load of
   SAVES/TS0438-M-T150.Civ5Save (one turn, to 151) with a server.cfg written here in hostruns.py's keys:
   L1  FIXED_BIN, run_dir and save paths with '/' separators (the 2026-11-17 incident's form): exit 0, no refused
       create, cache\\Civ5SavedGameDatabase.db written, "result: passed". Cap 8 GB.
   L1s FIXED_BIN, run_dir in its 8.3 short form, lower case: the same.
   L2  FIXED_BIN, the create made to fail (a folder named Civ5SavedGameDatabase.db in the cache folder): exit 2, the
       report names the create and "the load stops here", no exception, peak working set under 2 GB, no cap event,
       under 120 s. Cap 8 GB.
   L3  PIN_BIN (the server before the fix; negative control and the incident's reproduction), L1's '/' form, cap 4 GB:
       the create refused, then the runaway, held at the cap: exit non-zero, peak process commit at or under 4 GB
       (the job's own count), the exception's frames symbolized into DIR/L3/server-symbolized.log (CvMap::InitPlots).
Exit 0 when every check passes, 1 when one fails, 2 on a set-up or build error. DIR must be outside the repository.
Research: research/03-dll-engine-boundary/server-host.md section 18.
"""
