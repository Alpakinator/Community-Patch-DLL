def check(name, ok, detail=''):
    return rt.check(name, ok, detail if isinstance(detail, str) else repr(detail))


NOWIN = 0x08000000
SYMBOLIZER = Path(r'C:\Program Files\LLVM\bin\llvm-symbolizer.exe')
CANARY = ('#include <stdio.h>\n#include <stdlib.h>\nint main() { char* volatile p = (char*)malloc(16); p[16] = 1; '
          'printf("canary NOT caught\\n"); free(p); return 0; }\n')


def gen_header(out):
    m = BLOCK.search(SRC.read_text(encoding='utf-8'))
    if not m:
        return None
    h = out / 'runfolder.gen.h'
    h.write_text('// generated by server/tests/runfolder/run_runfolder_test.py from server/src/srv_ifaces.cpp\n'
                 '#pragma once\n#ifndef WIN32_LEAN_AND_MEAN\n#define WIN32_LEAN_AND_MEAN\n#endif\n#include <windows.h>\n'
                 '#include <string>\n' + m.group(0) + '\n', encoding='utf-8')
    return h


def run_cases(exe, work, tag, env=None):
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    cp = subprocess.run([str(exe), str(work)], capture_output=True, text=True, errors='replace', env=env,
                        creationflags=NOWIN, timeout=120)
    (work.parent / ('%s-output.txt' % tag)).write_text(cp.stdout + cp.stderr, encoding='utf-8')
    lines = [x for x in cp.stdout.splitlines() if x.startswith(('PASS ', 'FAIL '))]
    for x in lines:
        check('%s %s' % (tag, x[5:].split(' -- ')[0]), x.startswith('PASS '), x)
    m = re.search(r'^RESULT (\d+)/(\d+)', cp.stdout, re.M)
    check('%s: the program ran every case and exited 0 (%s)' % (tag, m.group(0) if m else 'no RESULT line'),
          cp.returncode == 0 and m is not None and m.group(1) == m.group(2) and int(m.group(2)) >= 25,
          'exit %s; %s' % (cp.returncode, (cp.stdout + cp.stderr)[-1500:]))
    return cp


def unit(out):
    b = out / 'clang'
    b.mkdir(parents=True, exist_ok=True)
    if not check('unit: the block "0488 RUN FOLDER" is in srv_ifaces.cpp', gen_header(b) is not None):
        return
    exe = b / 'test_runfolder.exe'
    cp = rt.tc.run_in_env('x64', [rt.tc.CLANG, '-m64', '/MD', '/O2', '/Zi', '/EHsc', '/std:c++14', '/W3', '/WX',
                                  '/D_CRT_SECURE_NO_WARNINGS', '-fuse-ld=lld', '/I' + str(b),
                                  str(HERE / 'test_runfolder.cpp'), '/Fe' + str(exe), '/link', 'kernel32.lib'],
                          cwd=str(b))
    if check('unit: test_runfolder.cpp + the block build (clang-cl x64, /W3 /WX)', cp.returncode == 0 and exe.exists(),
             (cp.stdout + cp.stderr)[-2000:]):
        run_cases(exe, b / 'work', 'clang')


def unit_asan(out):
    env = rt.vcvars_env('x64')
    if not check('asan: vcvarsall x64', env is not None):
        return
    cl = shutil.which('cl', path=env.get('PATH', env.get('Path', '')))
    if not check('asan: cl.exe found', cl is not None):
        return
    d = out / 'asan'
    d.mkdir(parents=True, exist_ok=True)
    gen_header(d)
    (d / 'canary.cpp').write_text(CANARY, encoding='ascii')
    for exe, srcs, fl in (('canary.exe', [d / 'canary.cpp'], ['/nologo', '/Zi', '/Od', '/fsanitize=address']),
                          ('test_runfolder.exe', [HERE / 'test_runfolder.cpp'],
                           ['/nologo', '/EHsc', '/W3', '/WX', '/Zi', '/Oy-', '/fsanitize=address',
                            '/D_CRT_SECURE_NO_WARNINGS', '/I' + str(d)])):
        cp = subprocess.run([cl] + fl + [str(x) for x in srcs] + ['/Fe' + str(d / exe), '/Fo' + str(d) + '\\',
                                                                  '/Fd' + str(d / (exe + '.pdb')), '/link',
                                                                  'kernel32.lib'],
                            cwd=str(d), env=env, capture_output=True, text=True, errors='replace')
        if not check('asan: %s compiled with MSVC /fsanitize=address (x64)' % exe, cp.returncode == 0,
                     (cp.stdout + cp.stderr)[-2000:]):
            return
    cp = subprocess.run([str(d / 'canary.exe')], capture_output=True, text=True, errors='replace', env=env,
                        creationflags=NOWIN, timeout=60)
    check("asan (negative): the canary's heap-buffer-overflow is reported (ASan active)",
          cp.returncode != 0 and 'heap-buffer-overflow' in cp.stdout + cp.stderr, (cp.stdout + cp.stderr)[-600:])
    cp = run_cases(d / 'test_runfolder.exe', d / 'work', 'asan', env)
    check('asan: no AddressSanitizer report', 'AddressSanitizer' not in cp.stdout + cp.stderr,
          (cp.stdout + cp.stderr)[-1500:])


