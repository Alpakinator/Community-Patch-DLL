"""Generate stand-in DLL objects for the unit-feed tests (issue 4452, epic 0375, 2026-11-15).

    python -I server/tests/feed/gen_standins.py --src <DLL fork tree> --out <dir>/standins.gen.h

Reads the DLL interface classes the server's unit feed calls (ICvUnit1, ICvPlot1, ICvCity1, ICvCombatInfo1, ICvPlayer1,
ICvGame1, ICvGameContext1, ICvTeam1 (issue 0439), each with ICvUnknown's pure virtuals) from the fork's CvDllInterfaces.h with the parser of
tools/x64-dll/smoke-host/gen_ifaces.py, and writes for each a class `Stand_<I>` that overrides every pure virtual with
`StandHit("<I>::<name>"); return StandDefault<R>::Get();` (typed, so float, struct and reference returns are right on x64). A test derives from
it and overrides the getters it needs; nothing of the DLL's code is used. Exit 0 written, 1 a class not found.
"""
import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(REPO / 'tools' / 'x64-dll' / 'smoke-host'))
import gen_ifaces as gi  # noqa: E402

HEADER = r'CvGameCoreDLLUtil\include\CvDllInterfaces.h'
CLASSES = ['ICvUnit1', 'ICvPlot1', 'ICvCity1', 'ICvCombatInfo1', 'ICvPlayer1', 'ICvGame1', 'ICvGameContext1',
           'ICvTeam1']   # ICvTeam1: issue 0439 (kind 21's all-water passage)


def generate(src: Path) -> str:
    text = gi.strip_comments((src / HEADER).read_text(encoding='latin-1'))
    out = ['// Generated by server/tests/feed/gen_standins.py from the DLL fork headers. Do not edit.', '#pragma once',
           '#include <type_traits>', '',
           'template<class T> struct StandDefault { static T Get() { return T(); } };',
           'template<> struct StandDefault<void> { static void Get() {} };',
           '// a reference return (FAutoArchive& is an incomplete type here): a zeroed static block; never used, since the',
           '// call itself is reported by StandHit',
           'inline void* StandBlock() { alignas(16) static char s[4096] = {}; return s; }',
           'template<class T> struct StandDefault<T&> { static T& Get() { return *static_cast<T*>(StandBlock()); } };',
           'template<class T> struct StandDefault<T* const> { static T* Get() { return nullptr; } };',
           '// every default body reports itself: a test counts the calls the code under test made to a method it did not',
           '// model (the stand-in for "a DLL call not on the purity list"); defined by the test',
           'void StandHit(const char* szMethod);', '']
    for cls in CLASSES:
        methods = []
        for c in ('ICvUnknown', cls):
            for st in gi.statements(gi.class_body(text, c)):
                v = gi.parse_virtual(st)
                if v:
                    methods.append(v)
        out.append(f'class Stand_{cls} : public {cls}')
        out.append('{')
        out.append('public:')
        for m in methods:
            cc = (m['cc'] + ' ') if m['cc'] else ''
            const = ' const' if m['const'] else ''
            ret = m['ret']
            out.append(f'\t{ret} {cc}{m["name"]}({m["params_nodef"]}){const} override '
                       f'{{ StandHit("{cls}::{m["name"]}"); return StandDefault<{ret}>::Get(); }}')
        out.append('};')
        out.append('')
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--src', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    a = ap.parse_args()
    try:
        text = generate(a.src)
    except (OSError, RuntimeError) as e:
        print(f'gen_standins: {e}')
        return 1
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(text, encoding='utf-8')
    print(f'gen_standins: {a.out}: {len(CLASSES)} classes')
    return 0


if __name__ == '__main__':
    sys.exit(main())
