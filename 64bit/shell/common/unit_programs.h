// unit_programs.h - the EXE's unit programs as the compositor's unit-draw filter needs them (epic 0040, issue 4751;
// research/05-graphics-composition/unit-draw-filter.md 2, research/07-architecture-decisions/epic-0040-breakdown.md 1.2).
// Plain C data, no render header: shell_composite.dll (x86) and the server (x64) include it alike.
//
// The DROP table is exactly the pass-0 (scene and water reflection) (VS, PS) pairs the server's unit module draws:
// render/src/units/programs.cpp unitProgramTable(), its PassKind::Scene rows. render/tests/units/
// test_unit_programs_table.cpp checks that the two lists are equal; a program the server does not draw is never in it, so
// a draw the server would not replace is never dropped (breakdown 1.2, "the rule behind it").
// The KEEP table names programs the filter recognises and always passes (for its counters): the unit shadow-mask pass
// (pass 1, kept by 0375 decision 7 (c): stock's shadows reach the server's terrain through 0169's tap) and the selection
// effect over the selected unit (O4 (a), MC 2026-11-17 06:32: recognised and kept). Ticket 4785: the mask pass is dropped
// too while the server casts the units' shadows (VPMODE_UNIT_SHADOWS; kVPUnitMaskPairs below).
//
// Only SHA-256 digests of the DXBC containers are here (D83: digests, never bytes). exeVa is where build 4390913 of
// CivilizationV_DX11.exe holds the blob (informational; the filter matches by digest of the bytecode handed to
// ID3D11Device::CreateVertexShader / CreatePixelShader, which equals the blob [C, 4751: the 3907 exports' bytecode]).
#pragma once
#include <stdint.h>

#define VPUNIT_STAGE_VS 1u
#define VPUNIT_STAGE_PS 2u

// materials as bits of VPUnitProgram::materials
#define VPUNIT_MAT87 1u   /* UnitShader_CODE (static, non-skinned unit art) */
#define VPUNIT_MAT88 2u   /* UnitShader_Alpha_CODE: shares VS 82e59838 with 87; never drawn in the 3907 catalogue */
#define VPUNIT_MAT89 4u   /* UnitShader_SkinnedAlpha_CODE */
#define VPUNIT_MAT90 8u   /* UnitShader_Skinned_CODE */

typedef struct VPUnitProgram
{
	uint8_t sha256[32];   // digest of the DXBC container
	uint32_t exeVa;       // build 4390913 (informational)
	uint8_t stage;        // VPUNIT_STAGE_*
	uint8_t materials;    // VPUNIT_MAT* bits of the materials that use it in this pass
	uint8_t pass;         // 0 = scene and reflection, 1 = shadow mask, 0xFF = not a unit material (the selection effect)
	uint8_t pad;
} VPUnitProgram;

typedef struct VPUnitPair
{
	uint8_t material;     // 87, 89, 90
	uint8_t vs;           // index into the same table
	uint8_t ps;
	uint8_t pad;
} VPUnitPair;

